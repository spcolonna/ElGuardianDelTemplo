/// Reemplaza `{clave}` por su valor. `t('juego.mazo', {'n': 20})`.
String fmt(String plantilla, [Map<String, Object?> vals = const {}]) {
  var s = plantilla;
  vals.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}
